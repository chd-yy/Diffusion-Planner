# 使用指定的 Python 解释器启动 PyTorch 分布式训练任务。
#
# 整条命令较长，因此使用反斜杠：
#
# \
#
# 将一条命令拆分为多行书写。
#
# Shell 在执行时会将这些行拼接为一条完整命令。
#
# ------------------------------------------------------------
# sudo -E
# ------------------------------------------------------------
#
# sudo：
#   使用管理员权限运行后续命令。
#
# -E：
#   尝试保留当前用户的环境变量。
#
# 当前脚本前面已经设置了：
#
# CUDA_VISIBLE_DEVICES
#
# 使用 sudo -E 后，该环境变量可以继续传递给管理员权限下启动的程序。
#
# 注意：
# 使用 sudo 运行 Python 训练任务并非所有场景下都必需。
# 是否需要管理员权限，应当结合数据目录权限和运行环境判断。
# 本次仅添加注释，没有修改原始命令。
#
# ------------------------------------------------------------
# $RUN_PYTHON_PATH
# ------------------------------------------------------------
#
# 使用前面设置的 Python 解释器执行命令。
#
# 例如，变量替换后可能相当于执行：
#
# /home/xxx/anaconda3/envs/diffusion_planner/bin/python
#
# 这样可以确保程序使用正确的 Conda 环境以及其中安装的依赖。
#
# ------------------------------------------------------------
# -m torch.distributed.run
# ------------------------------------------------------------
#
# -m 表示将某个 Python 模块作为程序运行。
#
# torch.distributed.run 是 PyTorch 提供的分布式训练启动器。
#
# 它会创建多个训练进程，并为每个进程设置分布式训练所需的信息，
# 例如：
# 1. 当前进程的 rank；
# 2. 本机进程编号 local rank；
# 3. 总进程数 world size；
# 4. 进程之间通信所需的环境变量。
#
# 该写法与常见的 torchrun 命令作用接近。
#
# ------------------------------------------------------------
# --nnodes 1
# ------------------------------------------------------------
#
# 指定参与训练的机器数量。
#
# 当前值为：
#
# 1
#
# 表示只使用一台计算机进行训练。
#
# 这属于单机多 GPU 训练。
#
# ------------------------------------------------------------
# --nproc-per-node 8
# ------------------------------------------------------------
#
# 指定每一台机器需要启动多少个训练进程。
#
# 当前值为：
#
# 8
#
# 表示在当前机器上启动 8 个 Python 训练进程。
#
# 一般情况下，每个进程对应一张 GPU：
#
# 进程 0 → GPU 0
# 进程 1 → GPU 1
# 进程 2 → GPU 2
# ...
# 进程 7 → GPU 7
#
# 最终是否按照这种方式绑定 GPU，
# 还取决于 train_predictor.py 中的分布式初始化逻辑。
#
# ------------------------------------------------------------
# --standalone
# ------------------------------------------------------------
#
# 表示当前任务采用单机独立运行模式。
#
# PyTorch 会自动为分布式进程通信配置本地 rendezvous 服务。
#
# 当训练只在一台机器上运行时，
# 使用该参数可以简化分布式环境配置。
#
# ------------------------------------------------------------
# train_predictor.py
# ------------------------------------------------------------
#
# 表示真正需要执行的 Python 训练脚本。
#
# 分布式启动器会让 8 个进程分别运行该脚本。
#
# 在 train_predictor.py 内部，
# 通常还会进行以下操作：
# 1. 初始化 DDP；
# 2. 构造 DistributedSampler；
# 3. 创建模型；
# 4. 将模型包装为 DistributedDataParallel；
# 5. 执行训练循环；
# 6. 仅由主进程保存模型和打印日志。
sudo -E $RUN_PYTHON_PATH -m torch.distributed.run --nnodes 1 --nproc-per-node 8 --standalone train_predictor.py \

# 将训练数据目录传递给 train_predictor.py。
#
# --train_set 是 train_predictor.py 中定义的命令行参数。
#
# $TRAIN_SET_PATH 会被 Shell 替换为前面设置的训练数据路径。
#
# 原始代码中参数名和变量之间保留了两个空格。
# 这不会影响 Shell 对命令的解析。
--train_set  $TRAIN_SET_PATH \

# 将训练数据列表文件路径传递给 train_predictor.py。
