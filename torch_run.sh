# --train_set_list 是 train_predictor.py 中定义的命令行参数。
#
# $TRAIN_SET_LIST_PATH 会被 Shell 替换为前面设置的数据列表路径。
#
# 注意：
# 原始代码在这一行末尾保留了反斜杠。
#
# 反斜杠表示当前命令还可以在下一行继续书写其他参数。
#
# 如果实际脚本在这里结束，应当在运行前确认：
# 该反斜杠是否是作者有意保留的。
#
# 本次严格遵守要求，没有删除或修改该反斜杠。
--train_set_list  $TRAIN_SET_LIST_PATH \

